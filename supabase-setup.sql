-- Graph AI olay tablosu ve Row Level Security politikaları
-- Supabase SQL Editor'de proje sahibi/yetkili hesapla bir kez çalıştır.

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('visit', 'analiz')),
  asset_name text null check (asset_name is null or char_length(asset_name) <= 120),
  created_at timestamptz not null default now()
);

create index if not exists events_created_at_idx
  on public.events (created_at desc);

alter table public.events enable row level security;

grant insert on public.events to anon, authenticated;
grant select on public.events to authenticated;

-- Identity/serial sütununun varsayılan değer üretebilmesi için.
do $$
begin
  if to_regclass('public.events_id_seq') is not null then
    execute 'grant usage, select on sequence public.events_id_seq to anon, authenticated';
  end if;
end
$$;

drop policy if exists "Graph AI public event insert" on public.events;
create policy "Graph AI public event insert"
on public.events
for insert
to anon, authenticated
with check (
  event_type in ('visit', 'analiz')
  and (asset_name is null or char_length(asset_name) <= 120)
);

drop policy if exists "Graph AI admin event read" on public.events;
create policy "Graph AI admin event read"
on public.events
for select
to authenticated
using (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  or coalesce((auth.jwt() -> 'app_metadata' -> 'roles') ? 'admin', false)
);
