-- Grap-AI günlük yönetici izleme ajanı
-- Supabase SQL Editor'de bir kez çalıştır.
-- Raporları yalnızca app_metadata.role=admin olan kullanıcılar okuyabilir.
-- Servis anahtarı yalnızca GitHub Actions secret olarak tutulur; tarayıcıya konmaz.

create table if not exists public.admin_system_events (
  id bigint generated by default as identity primary key,
  device_id uuid not null,
  event_type text not null check (event_type in ('js_error', 'unhandled_rejection', 'resource_error', 'api_error')),
  source text not null default 'unknown',
  message text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_system_events_created_at_idx
  on public.admin_system_events (created_at desc);
create index if not exists admin_system_events_device_created_idx
  on public.admin_system_events (device_id, created_at desc);

alter table public.admin_system_events enable row level security;
revoke all on table public.admin_system_events from public, anon, authenticated;
grant select on table public.admin_system_events to authenticated;

drop policy if exists admin_system_events_admin_read on public.admin_system_events;
create policy admin_system_events_admin_read
  on public.admin_system_events
  for select
  to authenticated
  using (
    lower(coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '')) = 'admin'
    or exists (
      select 1
      from jsonb_array_elements_text(
        case
          when jsonb_typeof(auth.jwt() -> 'app_metadata' -> 'roles') = 'array'
            then auth.jwt() -> 'app_metadata' -> 'roles'
          else '[]'::jsonb
        end
      ) as roles(role)
      where lower(roles.role) = 'admin'
    )
  );

create or replace function public.grap_ai_log_system_event(
  p_event_type text,
  p_source text,
  p_message text,
  p_details jsonb,
  p_device_id uuid
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  v_recent_count integer;
  v_details jsonb;
begin
  if p_event_type is null or p_event_type not in (
    'js_error', 'unhandled_rejection', 'resource_error', 'api_error'
  ) then
    return false;
  end if;
  if p_device_id is null or p_message is null or length(trim(p_message)) = 0 then
    return false;
  end if;

  v_details := case
    when jsonb_typeof(p_details) = 'object' then p_details
    else '{}'::jsonb
  end;
  if octet_length(v_details::text) > 4000 then
    return false;
  end if;

  select count(*) into v_recent_count
  from public.admin_system_events
  where device_id = p_device_id
    and created_at > now() - interval '1 hour';

  if v_recent_count >= 30 then
    return false;
  end if;

  insert into public.admin_system_events (
    device_id, event_type, source, message, details
  ) values (
    p_device_id,
    p_event_type,
    left(regexp_replace(coalesce(p_source, 'unknown'), '[[:cntrl:]]', ' ', 'g'), 180),
    left(regexp_replace(p_message, '[[:cntrl:]]', ' ', 'g'), 500),
    v_details
  );

  return true;
end;
$function$;

revoke all on function public.grap_ai_log_system_event(text, text, text, jsonb, uuid) from public;
grant execute on function public.grap_ai_log_system_event(text, text, text, jsonb, uuid) to anon, authenticated;

